/**
 * Lists home-page hero rotator images from `public/images/sliding-gallery-hero/`.
 * Deterministically shuffles and picks 16 so builds are stable. Change HERO_GALLERY_SEED
 * or HERO_GALLERY_COUNT below to reshuffle/resize the set.
 * Run: npm run sync:hero-gallery
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const sub = 'sliding-gallery-hero';
const dir = path.join(root, 'public', 'images', sub);
const outFile = path.join(root, 'src', 'content', 'heroGalleryFilenames.ts');

const HERO_GALLERY_SEED = 0xC0FFEE42;
const HERO_GALLERY_COUNT = 18;
const IMAGE_EXTS = new Set(['.webp', '.png', '.jpg', '.jpeg']);

if (!fs.existsSync(dir)) {
  console.error('sync-hero-gallery: missing directory', dir);
  process.exit(1);
}

function seededShuffle(items, seed) {
  const arr = [...items];
  let s = seed >>> 0;
  const rnd = () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return (((t ^ (t >>> 14)) >>> 0) % 0xffffffff) / 0xffffffff;
  };
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

const all = fs
  .readdirSync(dir)
  .filter((f) => {
    if (f.startsWith('.') || f === 'Thumbs.db') return false;
    return IMAGE_EXTS.has(path.extname(f).toLowerCase());
  })
  .sort((a, b) => a.localeCompare(b, undefined, { sensitivity: 'base' }));

const picked = seededShuffle(all, HERO_GALLERY_SEED).slice(0, HERO_GALLERY_COUNT);

const escape = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

const body = `/**
 * Auto-generated by scripts/sync-hero-gallery.mjs - do not edit by hand.
 * Run: npm run sync:hero-gallery
 * Source: public/images/${sub}/ (random ${HERO_GALLERY_COUNT}, seeded for stable builds)
 */
export const HERO_GALLERY_FILENAMES = [
${picked.map((f) => `  '${escape(`images/${sub}/${f}`)}',`).join('\n')}
] as const;
`;

fs.writeFileSync(outFile, body, 'utf8');
console.log(
  `sync-hero-gallery: ${picked.length}/${all.length} image(s) from ${sub}/ \u2192 ${path.relative(root, outFile)}`,
);
